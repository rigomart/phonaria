import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

type PlanSample = { word: string; file: string; status: string; sha256?: string };
type Plan = {
	targetAccent: string;
	settings: { voiceId: string };
	samples: PlanSample[];
};

export type WordAudioManifestSource = { voice: string; words: string[] };

/** "en-US-JennyNeural" -> "jenny": the voice's name, lowercase, as its bucket folder. */
export function voiceFolderName(voiceId: string): string {
	const name = voiceId
		.split("-")
		.at(-1)
		?.replace(/Neural$/, "");
	if (!name || !/^[A-Za-z]+$/.test(name))
		throw new Error(`Cannot derive a voice name from "${voiceId}"`);
	return name.toLowerCase();
}

/** The recorded words of a fully generated plan. Refuses any unfinished or unusual sample. */
export function manifestFromPlan(plan: Plan): WordAudioManifestSource {
	const unfinished = plan.samples.filter(({ status, sha256 }) => status !== "generated" || !sha256);
	if (unfinished.length) {
		throw new Error(
			`${unfinished.length} samples are not generated: ${unfinished
				.slice(0, 5)
				.map(({ word }) => word)
				.join(", ")}`,
		);
	}
	const notOgg = plan.samples.filter(({ word, file }) => file !== `audio/${word}.ogg`);
	if (notOgg.length) {
		throw new Error(
			`Only Ogg recordings are published (audio/{word}.ogg); regenerate with --format=ogg: ${notOgg
				.slice(0, 5)
				.map(({ file }) => file)
				.join(", ")}`,
		);
	}
	const words = plan.samples.map(({ word }) => word);
	const invalid = words.filter((word) => !/^[a-z]+$/.test(word));
	if (invalid.length) throw new Error(`Words must be lowercase a-z: ${invalid.join(", ")}`);
	if (new Set(words).size !== words.length) throw new Error("The plan lists a word twice");
	return { voice: voiceFolderName(plan.settings.voiceId), words: words.sort() };
}

/** Per-accent module path and export name in @phonaria/phonetics-data. */
const MANIFEST_TARGETS: Record<string, { file: string; exportName: string }> = {
	"en-us": { file: "src/languages/en/word-audio.ts", exportName: "EnglishWordAudio" },
};

export function manifestTarget(targetAccent: string) {
	const target = MANIFEST_TARGETS[targetAccent];
	if (!target) throw new Error(`No word-audio manifest module for accent "${targetAccent}"`);
	return target;
}

export function renderManifestModule(
	targetAccent: string,
	manifest: WordAudioManifestSource,
): string {
	const { exportName } = manifestTarget(targetAccent);
	const words = manifest.words.map((word) => `\t\t${JSON.stringify(word)},\n`).join("");
	return `// Generated by \`bun run --cwd packages/audio-gen manifest\`. Do not edit by hand.
import { deepFreeze } from "../../shared/readonly";
import type { WordAudioManifest } from "../types";

/** Words with a recording at \`audio/${targetAccent}/words/${manifest.voice}/{word}.ogg\` in the public assets bucket. */
export const ${exportName}: WordAudioManifest = deepFreeze({
	voice: ${JSON.stringify(manifest.voice)},
	words: [
${words}	],
});
`;
}

/** Write the committed manifest module for a completed output directory. */
export function writeManifest(outputDir: string, phoneticsDataDir: string): string {
	const plan = JSON.parse(readFileSync(path.join(outputDir, "plan.json"), "utf8")) as Plan;
	const manifest = manifestFromPlan(plan);
	const target = path.join(phoneticsDataDir, manifestTarget(plan.targetAccent).file);
	writeFileSync(target, renderManifestModule(plan.targetAccent, manifest));
	return target;
}
