#!/usr/bin/env bun
/**
 * Write the accepted pronunciations of every minimal-pair catalog word to
 * `src/lib/speech/catalog-pronunciations.ts`. The speech scoring route reads that
 * small map so the Worker never bundles the curated top-10k dictionary.
 *
 * Run after the contrast catalog or the curated dictionary changes:
 * `bun apps/phonaria/scripts/generate-speech-words.ts`
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
	EnglishPhonemeContrasts,
	type PhonemeContrast,
	type PhonemeSymbolId,
	toBasePhonemeIds,
} from "@phonaria/phonetics-data";
import { EnglishCuratedTop10k } from "@phonaria/phonetics-data/data/en/curated-10k";

export const CATALOG_PRONUNCIATIONS_PATH = resolve(
	import.meta.dirname,
	"../src/lib/speech/catalog-pronunciations.ts",
);

type Dictionary = Readonly<Record<string, readonly string[] | undefined>>;

/** Each catalog word's distinct pronunciations as base phoneme IDs, words in alphabetical order. */
export function buildCatalogPronunciations(
	contrasts: readonly PhonemeContrast<"en-us">[] = EnglishPhonemeContrasts,
	dictionary: Dictionary = EnglishCuratedTop10k.words,
): Record<string, PhonemeSymbolId[][]> {
	const words = [
		...new Set(contrasts.flatMap(({ minimalPairs }) => minimalPairs.flatMap(({ words }) => words))),
	].sort();
	return Object.fromEntries(
		words.map((word) => {
			const variants = dictionary[word];
			if (!variants) throw new Error(`"${word}" isn't in the curated top-10k dictionary`);
			const distinct = [...new Set(variants.map((variant) => toBasePhonemeIds(variant).join(" ")))];
			return [word, distinct.map((ids) => ids.split(" ") as PhonemeSymbolId[])];
		}),
	);
}

export function formatCatalogPronunciations(
	pronunciations: Record<string, PhonemeSymbolId[][]>,
): string {
	const entries = Object.entries(pronunciations).map(([word, variants]) => {
		const value = variants.map((ids) => `[${ids.map((id) => `"${id}"`).join(", ")}]`).join(", ");
		return `\t[${JSON.stringify(word)}, [${value}]],`;
	});
	return [
		"// Generated by `bun apps/phonaria/scripts/generate-speech-words.ts`. Do not edit by hand.",
		'import type { PhonemeSymbolId } from "@phonaria/phonetics-data";',
		"",
		"/** Accepted pronunciations of each en-us minimal-pair catalog word, as base phoneme IDs. */",
		"export const CatalogWordPronunciations = new Map<string, readonly (readonly PhonemeSymbolId[])[]>([",
		...entries,
		"]);",
		"",
	].join("\n");
}

if (import.meta.main) {
	writeFileSync(
		CATALOG_PRONUNCIATIONS_PATH,
		formatCatalogPronunciations(buildCatalogPronunciations()),
	);
}
